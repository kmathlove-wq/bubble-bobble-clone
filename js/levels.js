// ===== levels.js =====
// 판 데이터. 한 판 = { time(초), theme, map:[문자열 24줄, 각 32칸] }.
// 글자:  '#'=발판  '.'=빈칸  'P'=주인공  '1'=통통이  '2'=콩콩이  '3'=날개몬
// 발판은 세로로 3칸(48px) 간격 → 점프 한 번으로 위층에 닿는다.
// 뒤로 갈수록 시간이 짧고 적이 많고 사납다. (M8에서 30판+ 로 확장)
(function (BB) {

  // 공통 뼈대 (지형.png 를 옮긴 것) — 3층 발판 구조
  var BASE = [
    "################################",
    "#..............................#",
    "#..............................#",
    "#..............................#",
    "#..............................#",
    "#####......##########......#####",
    "#..............................#",
    "#..............................#",
    "#..########..........########..#",
    "#..............................#",
    "#..............................#",
    "#######......######......#######",
    "#..............................#",
    "#..............................#",
    "#..########..........########..#",
    "#..............................#",
    "#..............................#",
    "#####......##########......#####",
    "#..............................#",
    "#..............................#",
    "#..######..............######..#",
    "#..............................#",
    "#..P.......................P...#",
    "################################"
  ];

  // 뼈대에 적 글자를 얹어 판을 만든다 (row, col, char)
  function make(time, theme, placements) {
    var m = BASE.slice();
    m[22] = "#..P...........................#"; // 주인공 한 명만
    placements.forEach(function (p) {
      var row = m[p[0]].split('');
      row[p[1]] = p[2];
      m[p[0]] = row.join('');
    });
    return { time: time, theme: theme, map: m };
  }

  BB.LEVELS = [
    // 1 — 아주 쉬움
    make(45, 'pink', [[2, 10, '1'], [2, 20, '1']]),
    // 2
    make(42, 'pink', [[2, 8, '1'], [2, 16, '1'], [6, 24, '1']]),
    // 3 — 콩콩이 등장
    make(40, 'sky', [[2, 6, '1'], [2, 22, '1'], [9, 14, '2']]),
    // 4
    make(38, 'sky', [[2, 10, '1'], [6, 6, '2'], [6, 24, '2'], [13, 16, '1']]),
    // 5 — 날개몬 등장
    make(36, 'lime', [[2, 12, '1'], [2, 18, '2'], [12, 8, '3']]),
    // 6
    make(34, 'lime', [[2, 8, '2'], [2, 22, '2'], [9, 6, '1'], [9, 24, '1'], [15, 16, '3']]),
    // 7 — 사용자가 직접 꾸며볼 판 (지금은 기본값)
    make(32, 'gold', [[2, 10, '3'], [2, 20, '3'], [9, 15, '2']]),
    // 8 — 북적북적
    make(30, 'grape', [[2, 6, '1'], [2, 14, '2'], [2, 24, '1'], [9, 10, '2'], [9, 20, '2'], [15, 15, '3']])
  ];
})(window.BB);
